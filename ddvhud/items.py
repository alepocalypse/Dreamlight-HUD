def item_name(item_id):
    return ITEMS.get(item_id) or f"Item #{item_id}"


def item_wiki_title(item_id):
    """The wiki page title for an item: its display name unless overridden.
    Returns (title, found); found is False when the wiki has no page (link a search for the title).
    None for an id missing from the table."""
    name = ITEMS.get(item_id)
    if name is None:
        return None
    if item_id in WIKI_OVERRIDES:
        title = WIKI_OVERRIDES[item_id]
        return (title, True) if title else (name, False)
    return name, True
