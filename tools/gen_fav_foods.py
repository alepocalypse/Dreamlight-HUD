"""Print ddvhud/fav_foods.py: the favorite food of each kind of Critter, from dreamlightvalleywiki.com (read-only).
Each Companion's wiki page has |favfood=; a species' Classic one (else its first) stands for the species.
Usage: python3 tools/gen_fav_foods.py > ddvhud/fav_foods.py
"""
import json
import re
import sys
import urllib.parse
import urllib.request

sys.path.insert(0, ".")
from ddvhud.companions import COMPANIONS

API = "https://dreamlightvalleywiki.com/api.php"


def fetch(titles):
    q = urllib.parse.urlencode({"action": "query", "prop": "revisions", "rvprop": "content", "rvslots": "main",
                                "redirects": 1, "format": "json", "titles": "|".join(titles)})
    req = urllib.request.Request(API + "?" + q, headers={"User-Agent": "Mozilla/5.0"})
    data = json.load(urllib.request.urlopen(req))["query"]
    back = {r["to"]: r["from"] for r in data.get("redirects", [])}
    for page in data["pages"].values():
        if "revisions" in page:
            yield back.get(page["title"], page["title"]), page["revisions"][0]["slots"]["main"]["*"]


def plain(raw):
    raw = re.sub(r"<!--.*?-->", "", raw, flags=re.S)
    raw = re.sub(r"\{\{\s*name\s*\|([^|}]+)[^}]*\}\}", r"\1", raw, flags=re.I)
    raw = re.sub(r"\{\{.*?\}\}", "", raw)
    raw = re.sub(r"\[\[(?:[^|\]]*\|)?([^\]]+)\]\]", r"\1", raw)
    raw = re.sub(r"<br\s*/?>", ", ", raw).replace("}}", "")
    raw = re.sub(r"\b(\w{4,})\1\b", r"\1", raw)   # an icon's label printed twice ('DessertsDesserts')
    return re.sub(r"\s+", " ", raw).strip(" ,")


species = {}
for _id, (name, sp, _job) in COMPANIONS.items():
    species.setdefault(sp, []).append(name)
pick = {sp: next((n for n in names if n.startswith("Classic")), names[0]) for sp, names in species.items()}
pages = {}
titles = sorted(set(pick.values()))
for k in range(0, len(titles), 40):
    pages.update(dict(fetch(titles[k:k + 40])))
print('"""Generated by tools/gen_fav_foods.py from dreamlightvalleywiki.com; do not edit.')
print("FAV_FOODS: Critter species (as ddvhud/companions.py names it) -> its favorite food, in the wiki's words.\"\"\"")
print("FAV_FOODS = {")
for sp, title in sorted(pick.items()):
    m = re.search(r"\|\s*favfood\s*=([^\n]*)", pages.get(title, ""))
    food = plain(m.group(1)) if m else ""
    if food:
        print(f"    {sp!r}: {food!r},  # {title}")
print("}")
