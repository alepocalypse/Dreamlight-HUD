"""Print ddvhud/cookbook_data.py from the game's ActivityData.json. Read-only.

RECIPE_MEALS: the recipe id the save's Player.Cookbook.Recipes lists (ActivityData ids 2050000xxx, named
'Meal!...') -> the meal item it makes (field 7), so a meal the player has discovered can be told apart.
Usage: python3 tools/gen_cookbook.py [StreamingAssets/itemlist dir] > ddvhud/cookbook_data.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from gen_stock import DEFAULT, records

MEAL_BLOCK = 303   # item ids // 100000


def main(folder):
    data = open(os.path.join(folder, "ActivityData.json"), "rb").read()
    print('"""Generated by tools/gen_cookbook.py from the game\'s ActivityData.json; do not edit."""')
    print("RECIPE_MEALS = {")
    for i, d in records(data, 2050000000, 2050001000):
        meal = d.get(7)
        if d[2].startswith(b"Meal!") and meal and meal // 100000 == MEAL_BLOCK:
            print(f"    {i}: {meal},")
    print("}")


if __name__ == "__main__":
    main(os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else DEFAULT))
