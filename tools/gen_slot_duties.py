"""Print ddvhud/slot_text.py: the text and Rewards of the rotating Dreamlight Duties and Mist Duties. Read-only.

Each duty the save's Player.DutySlots names (DutyId) is a DutyAch record (itemlist/DutyAch.json: id, internal
name, text key) whose English text is that key's entry in DutyAch.locbin, a template with {TargetAmount} and
sometimes {ItemName} (LocDB_en-US.zip, read in memory, parsed as tools/gen_duties.py does).
The DutyAch record's field 13 lists its rewards, each a field-2 entry {1: currency id, 2: amount}; only the
rotating duties have them (the achievements sharing the file do not). Which currency a village's set pays is field
15 of that village's Scene.json record ('Village!...'). Currency names are each Currency.json record's
'Currency.<name>_DisplayName' entry in Currency.locbin.
Usage: python3 tools/gen_slot_duties.py [StreamingAssets dir] > ddvhud/slot_text.py
"""
import os
import re
import sys
import zipfile

import gen_duties
import gen_stock

DEFAULT = "~/.local/share/Steam/steamapps/common/Disney Dreamlight Valley/ddv_Data/StreamingAssets"


def currency_names(folder, loc):
    names = gen_duties.parse_locbin(loc.read("Currency.locbin"))
    data = open(os.path.join(folder, "itemlist", "Currency.json"), "rb").read()
    out = {}
    for i, d in gen_stock.records(data, 80000000, 81000000):
        key = d[3].decode().removeprefix("Currency.") if isinstance(d.get(3), bytes) else ""
        if names.get(key):
            out[i] = names[key].replace("\u00a0", " ")
    return out


def village_currencies(folder, names):
    scenes = open(os.path.join(folder, "itemlist", "Scene.json"), "rb").read()
    return {i: names[d[15]] for i, d in gen_stock.records(scenes, 1540000000, 1541000000)
            if d[2].startswith(b"Village!") and d.get(15) in names}


def rewards(d, names):
    out = {}
    for f, v in gen_stock.fields(d[13]) if isinstance(d.get(13), bytes) else []:
        if f == 2 and isinstance(v, bytes):
            e = dict(gen_stock.fields(v))
            if e.get(1) in names and e.get(2):
                out[names[e[1]]] = e[2]
    return out


def main(folder):
    loc = zipfile.ZipFile(os.path.join(folder, "Localization", "LocDB_en-US.zip"))
    text = gen_duties.parse_locbin(loc.read("DutyAch.locbin"))
    names = currency_names(folder, loc)
    items = open(os.path.join(folder, "itemlist", "DutyAch.json"), "rb").read()
    rows, paid = {}, {}
    for i, d in gen_stock.records(items, 2110000000, 2111000000):
        if rewards(d, names):
            paid.setdefault(i, rewards(d, names))
        # the record names its own text key (field 7, 'DutyAch.<key>'); it is not always '<name>_Description'
        key = d[7].decode().removeprefix("DutyAch.") if isinstance(d.get(7), bytes) else d[2].decode() + "_Description"
        t = text.get(key) or text.get(d[2].decode() + "_Description")
        if t:
            rows.setdefault(i, t.replace("\u00a0", " "))
    print('"""The text and Rewards of the rotating Dreamlight Duties (Valley) and Mist Duties (Eternity Isle).\n')
    print("Generated by tools/gen_slot_duties.py from the game's DutyAch.json, Scene.json, Currency.json and LocDB_en-US.zip")
    print("(DutyAch.locbin, Currency.locbin); do not edit, regenerate with: python3 tools/gen_slot_duties.py > ddvhud/slot_text.py")
    print("SLOT_TEXT: DutyId -> template ({TargetAmount}, sometimes {ItemName}). SLOT_TITLES: the save's Player.DutySlots")
    print("village key -> the in-game name of its set (menu.locbin). SLOT_CURRENCY: village key -> the currency its set")
    print('pays. SLOT_REWARDS: DutyId -> {currency: amount}, for the rotating duties only."""')
    print('SLOT_TITLES = {"1540000000": "Dreamlight Duties", "1540000101": "Mist Duties"}')
    print("SLOT_CURRENCY = {")
    for i, c in sorted(village_currencies(folder, names).items()):
        print(f'    "{i}": {c!r},')
    print("}")
    print("SLOT_REWARDS = {")
    for i, r in sorted(paid.items()):
        print(f"    {i}: {r!r},")
    print("}")
    print("SLOT_TEXT = {")
    for i, t in sorted(rows.items()):
        print(f"    {i}: {t!r},")
    print("}")


main(os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else DEFAULT))
