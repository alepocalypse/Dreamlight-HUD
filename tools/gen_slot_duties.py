"""Print ddvhud/slot_text.py: the text of the rotating Dreamlight Duties and Mist Duties. Read-only.

Each duty the save's Player.DutySlots names (DutyId) is a DutyAch record (itemlist/DutyAch.json: id, internal
name, text key) whose English text is that key's entry in DutyAch.locbin, a template with {TargetAmount} and
sometimes {ItemName} (LocDB_en-US.zip, read in memory, parsed as tools/gen_duties.py does).
Usage: python3 tools/gen_slot_duties.py [StreamingAssets dir] > ddvhud/slot_text.py
"""
import os
import re
import sys
import zipfile

import gen_duties
import gen_stock

DEFAULT = "~/.local/share/Steam/steamapps/common/Disney Dreamlight Valley/ddv_Data/StreamingAssets"


def main(folder):
    text = gen_duties.parse_locbin(zipfile.ZipFile(os.path.join(folder, "Localization", "LocDB_en-US.zip")).read("DutyAch.locbin"))
    items = open(os.path.join(folder, "itemlist", "DutyAch.json"), "rb").read()
    rows = {}
    for i, d in gen_stock.records(items, 2110000000, 2111000000):
        # the record names its own text key (field 7, 'DutyAch.<key>'); it is not always '<name>_Description'
        key = d[7].decode().removeprefix("DutyAch.") if isinstance(d.get(7), bytes) else d[2].decode() + "_Description"
        t = text.get(key) or text.get(d[2].decode() + "_Description")
        if t:
            rows.setdefault(i, t.replace("\u00a0", " "))
    print('"""The text of the rotating Dreamlight Duties (Valley) and Mist Duties (Eternity Isle).\n')
    print("Generated by tools/gen_slot_duties.py from the game's DutyAch.json and LocDB_en-US.zip (DutyAch.locbin);")
    print("do not edit. SLOT_TEXT: DutyId -> template ({TargetAmount}, sometimes {ItemName}). SLOT_TITLES: the save's")
    print('Player.DutySlots village key -> the in-game name of its set (menu.locbin)."""')
    print('SLOT_TITLES = {"1540000000": "Dreamlight Duties", "1540000101": "Mist Duties"}')
    print("SLOT_TEXT = {")
    for i, t in sorted(rows.items()):
        print(f"    {i}: {t!r},")
    print("}")


main(os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else DEFAULT))
