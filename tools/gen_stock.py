"""Print ddvhud/stock_data.py from the game's item data. Read-only.

SPECIAL_GEMS: MiningData id (what the save's Special mining rock names) -> the gem it yields, from
ActivityData.json (ids 2050200xxx; field 6 holds the item). GEM_COLOURS: gem item id -> colour, from the
gem's tag ids in ActivityItem.json (ids 2000700000-10, see ddvhud/duty_requirements.COLOUR_TAGS).
WILD_CROPS: wild seed item id (the save's wild plots hold these) -> the crop it yields, matched by the
seed's internal name ('WildCrop!MushroomSeed' -> 'Vegetable!Mushroom') in ActivityItem.json.
FLOWER_COLOURS: flower item id -> colours, read from the colour words ending its internal name (the
flowers carry no colour tag record we could find).
FRUIT_TREES: fruit tree sapling id (the save's fruit trees hold these as their planted seed) -> (the fruit it
grows, field 13; fruit per pick, field 14), from the 'FruitTree!...' seeds in ActivityItem.json.
Usage: python3 tools/gen_stock.py [StreamingAssets/itemlist dir] > ddvhud/stock_data.py
"""
import os
import re
import sys

DEFAULT = "~/.local/share/Steam/steamapps/common/Disney Dreamlight Valley/ddv_Data/StreamingAssets/itemlist"
COLOURS = ("Blue", "Green", "Red", "Pink", "White", "Black", "Yellow", "Orange", "Brown", "Purple", "Gray")
GEM_BLOCK, FLOWER_BLOCK = 316, 308


def varint(b, i):
    r = s = 0
    while True:
        x = b[i]; i += 1; r |= (x & 0x7F) << s; s += 7
        if x < 0x80:
            return r, i


def fields(b):
    i, out = 0, []
    while i < len(b):
        k, i = varint(b, i)
        w = k & 7
        if w == 0:
            v, i = varint(b, i)
        elif w == 2:
            n, i = varint(b, i); v = b[i:i + n]; i += n
        elif w in (1, 5):
            n = 8 if w == 1 else 4; v = b[i:i + n]; i += n
        else:
            raise ValueError(w)
        out.append((k >> 3, v))
    return out


def records(b, lo, hi):
    """(id, {field: first value}) for each record whose id is in [lo, hi): records are length-prefixed
    and start with 0x08 id-varint 0x12 name."""
    for m in re.finditer(rb"\x08", b):
        try:
            i, j = varint(b, m.end())
        except IndexError:
            continue
        if not lo <= i < hi or j >= len(b) or b[j] != 0x12:
            continue
        for back in (1, 2):
            try:
                n, end = varint(b, m.start() - back)
                if end != m.start():
                    continue
                rec = fields(b[m.start():m.start() + n])
            except (ValueError, IndexError):
                continue
            if rec and rec[0] == (1, i):
                d = {}
                for f, v in rec:
                    d.setdefault(f, v)
                yield i, d
                break


def main(folder):
    data = open(os.path.join(folder, "ActivityData.json"), "rb").read()
    items = open(os.path.join(folder, "ActivityItem.json"), "rb").read()
    gems, flowers = {}, {}
    for i, d in records(items, GEM_BLOCK * 100000, (GEM_BLOCK + 1) * 100000):
        packed = d.get(9, b"")
        tags = [packed] if isinstance(packed, int) else []
        q = 0
        while not tags and q < len(packed):
            t, q = varint(packed, q); tags.append(t)
        found = [COLOURS[t - 2000700000] for t in tags if 2000700000 <= t < 2000700000 + len(COLOURS)]
        if found:
            gems[i] = found[0]
    for i, d in records(items, FLOWER_BLOCK * 100000, (FLOWER_BLOCK + 1) * 100000):
        name = d[2].decode().split("!")[-1]
        if name.startswith(("Mission", "MRQS", "RLM", "VLG", "SEC", "RPT")) or "!Mission!" in d[2].decode():
            continue
        found = tuple(c for c in COLOURS if c in name)
        if found:
            flowers[i] = found
    seeds = {i: d[2].decode() for i, d in records(items, 304 * 100000, 305 * 100000) if d[2].startswith(b"WildCrop!")}
    crops = {i: d[2].decode() for i, d in records(items, 302 * 100000, 303 * 100000)}
    wild = {}
    for i, name in seeds.items():
        base = re.sub(r"[^a-z]", "", re.sub(r"_?Seed$", "", name.split("!")[-1]).lower())
        hit = [c for c, cn in crops.items() if re.sub(r"[^a-z]", "", cn.split("!")[-1].lower()) == base]
        if len(hit) == 1:
            wild[i] = hit[0]
    trees = {i: (d[13], d[14]) for i, d in records(items, 304 * 100000, 305 * 100000)
             if d[2].startswith(b"FruitTree!") and isinstance(d.get(13), int) and isinstance(d.get(14), int)}
    special = {}
    for i, d in records(data, 2050200000, 2050200300):
        gem = varint(d[6], 1)[0] if 6 in d and d[6][:1] == b"\x08" else 0
        if gem in gems:
            special[i] = gem
    print('"""Generated by tools/gen_stock.py from the game\'s ActivityData.json and ActivityItem.json; do not edit."""')
    print("SPECIAL_GEMS = {")
    for i, g in sorted(special.items()):
        print(f"    {i}: {g},")
    print("}\nGEM_COLOURS = {")
    for i, c in sorted(gems.items()):
        print(f"    {i}: {c!r},")
    print("}\nWILD_CROPS = {")
    for i, c in sorted(wild.items()):
        print(f"    {i}: {c},")
    print("}\nFLOWER_COLOURS = {")
    for i, c in sorted(flowers.items()):
        print(f"    {i}: {c!r},")
    print("}\nFRUIT_TREES = {")
    for i, t in sorted(trees.items()):
        print(f"    {i}: {t},")
    print("}")


if __name__ == "__main__":
    main(os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else DEFAULT))
