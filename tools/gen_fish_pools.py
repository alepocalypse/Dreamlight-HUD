"""Print ddvhud/fish_pools.py from dreamlightvalleywiki.com (MediaWiki API, read-only).
Each fish page's infobox has |pool=, written {{pool|Blue}}, can be {{pool|White}} or just Gold: the ripple
colour to fish in, then the others it can come from. 'None' means open water, no ripple needed. Fish are the items
ddvhud/spawns.py lists as Fishing.
Usage: python3 tools/gen_fish_pools.py > ddvhud/fish_pools.py
"""
import json
import re
import sys
import urllib.parse
import urllib.request

sys.path.insert(0, ".")
from ddvhud.items import ITEMS
from ddvhud.spawns import SPAWNS

API = "https://dreamlightvalleywiki.com/api.php"


def fetch(titles):
    q = urllib.parse.urlencode({"action": "query", "prop": "revisions", "rvprop": "content", "rvslots": "main",
                                "redirects": 1, "format": "json", "titles": "|".join(titles)})
    req = urllib.request.Request(API + "?" + q, headers={"User-Agent": "Mozilla/5.0"})
    data = json.load(urllib.request.urlopen(req))["query"]
    back = {r["to"]: r["from"] for r in data.get("redirects", [])}
    for page in data["pages"].values():
        revs = page.get("revisions")
        if revs:
            yield back.get(page["title"], page["title"]), revs[0]["slots"]["main"]["*"]


fish = {i: ITEMS[i] for i, (how, _) in SPAWNS.items() if how == "Fishing" and i in ITEMS}
by_name = {}
names = sorted(set(fish.values()))
for k in range(0, len(names), 40):
    by_name.update(dict(fetch(names[k:k + 40])))
print('"""Generated by tools/gen_fish_pools.py from dreamlightvalleywiki.com fish pages; do not edit.')
print("FISH_POOLS: fish item id -> the ripple colours it comes from, the usual one first ('Blue', 'White', 'Gold');")
print("'None' means open water, no ripple needed; an empty tuple (event fish) means the wiki says nothing.\"\"\"")
print("FISH_POOLS = {")
for i, n in sorted(fish.items()):
    text = by_name.get(n, "")
    m = re.search(r"\|\s*pool\s*=([^\n]*)", text)
    if not m:
        continue
    pools = tuple(re.findall(r"\b(White|Blue|Gold|None)\b", re.sub(r"<!--.*?-->", "", m.group(1))))
    print(f"    {i}: {pools!r},  # {n}")
print("}")
