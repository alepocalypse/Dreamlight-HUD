"""Print ddvhud/event_duty_data.py: the seasonal Event duties (Trick-or-Treat, Christmas, Spring, ...). Read-only.

The save keeps an Event duty as an entry of Player.AchievementsData (AchievementID, CurAmount,
ClaimedRewardMilestone, State) and nothing else, so its name, what it asks and its milestones come from the
game's data: each is a DutyAch record (itemlist/DutyAch.json, ids 2110100xxx, the file the rotating duties
share; parsed as tools/gen_stock.records does, repeated fields kept). Field 2 is the internal name
('Halloween_SugarRush': the Event's key before the first '_' or digit, then the duty), fields 7 and 8 the
keys of its title and description in DutyAch.locbin (the description is the designers' note, behind a
'{DoNotTranslate}' or '{Placeholder}' tag), and field 13, repeated, one milestone each: {1: count, 2: reward item id, 3: amount}.
Event duties are the records whose milestones pay items; the permanent Dreamlight duties in the same file
pay a currency (ids 80xxxxxx) and are left out. A reward item's English name is '<internal name>_DisplayName'
in whichever .locbin holds it, the internal name found by its id in whichever itemlist/*.json holds the item.
Usage: python3 tools/gen_event_duties.py [StreamingAssets dir] > ddvhud/event_duty_data.py
"""
import glob
import os
import re
import sys
import zipfile

import gen_duties
import gen_stock

DEFAULT = "~/.local/share/Steam/steamapps/common/Disney Dreamlight Valley/ddv_Data/StreamingAssets"
CURRENCY = range(80000000, 81000000)
KEY = re.compile(r"^([A-Za-z]+?)(?:_|\d)")


def records(data, lo, hi):
    """(id, {field: [every value]}) for each record whose id is in [lo, hi), repeated fields kept in order."""
    for m in re.finditer(rb"\x08", data):
        try:
            i, j = gen_stock.varint(data, m.end())
        except IndexError:
            continue
        if not lo <= i < hi or j >= len(data) or data[j] != 0x12:
            continue
        for back in (1, 2):
            try:
                n, end = gen_stock.varint(data, m.start() - back)
                if end != m.start():
                    continue
                rec = gen_stock.fields(data[m.start():m.start() + n])
            except (ValueError, IndexError):
                continue
            if rec and rec[0] == (1, i):
                d = {}
                for f, v in rec:
                    d.setdefault(f, []).append(v)
                yield i, d
                break


def text_of(d, field, loc):
    key = d[field][0].decode().removeprefix("DutyAch.") if isinstance(d.get(field, [None])[0], bytes) else ""
    text = re.sub(r"^\{[A-Za-z]+\}", "", loc.get(key, ""))   # '{DoNotTranslate}', '{Placeholder}'
    return text.replace("\u00a0", " ").strip()


def event_duties(folder, loc):
    data = open(os.path.join(folder, "itemlist", "DutyAch.json"), "rb").read()
    out = {}
    for i, d in records(data, 2110100000, 2111000000):
        milestones = [dict(gen_stock.fields(m)) for m in d.get(13, [])]
        if not milestones or any(m.get(2, 0) in CURRENCY or not m.get(1) for m in milestones):
            continue
        name = d[2][0].decode()
        key = KEY.match(name)
        if not key:
            continue
        out[i] = (key.group(1), text_of(d, 7, loc), text_of(d, 8, loc), [(m[1], m[2]) for m in milestones])
    return out


def item_names(folder, ids, names):
    """{item id: English name} for the ids found in any itemlist file, by '<internal name>_DisplayName'."""
    lo, hi = min(ids), max(ids) + 1
    out = {}
    for path in sorted(glob.glob(os.path.join(folder, "itemlist", "*.json"))):
        data = open(path, "rb").read()
        for i, d in records(data, lo, hi):
            internal = d[2][0].decode(errors="replace") if i in ids and isinstance(d.get(2, [None])[0], bytes) else None
            if internal and names.get(internal + "_DisplayName"):
                out.setdefault(i, names[internal + "_DisplayName"].replace(" ", " "))
    return out


def main(folder):
    loc = zipfile.ZipFile(os.path.join(folder, "Localization", "LocDB_en-US.zip"))
    names = {}
    for member in loc.namelist():
        names.update(gen_duties.parse_locbin(loc.read(member)))
    duties = event_duties(folder, names)
    rewards = item_names(folder, {item for _, _, _, ms in duties.values() for _, item in ms}, names)
    print('"""The seasonal Event duties: what the save calls achievements (Player.AchievementsData).')
    print()
    print("Generated by tools/gen_event_duties.py from the game's DutyAch.json and LocDB_en-US.zip; do not edit, regenerate")
    print("with: python3 tools/gen_event_duties.py > ddvhud/event_duty_data.py")
    print("EVENT_DUTIES: AchievementID -> (event key, title, what it asks (the designers' note), milestones [(count, reward")
    print('item name or "Item #id")]). The Event key is the internal name\'s prefix (Halloween, Christmas, Spring, ...)."""')
    print("EVENT_DUTIES = {")
    for i in sorted(duties):
        key, title, desc, milestones = duties[i]
        ms = [(count, rewards.get(item, f"Item #{item}")) for count, item in milestones]
        print(f"    {i}: ({key!r}, {title!r}, {desc!r}, {ms!r}),")
    print("}")


if __name__ == "__main__":
    main(os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else DEFAULT))
